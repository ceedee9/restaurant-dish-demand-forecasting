# ── Input/Output schemas ──────────────────────────────────────────────────────

class PredictionInput(BaseModel):
    dish_name    : str = Field(..., description="Name of the Filipino dish",
                               example="Sinigang na Salmon sa Miso")
    day_of_week  : str = Field(..., description="Day of the week",
                               example="Monday")
    weather      : str = Field(..., description="Weather condition",
                               example="Rainy")
    is_holiday   : int = Field(..., description="1 if Philippine public holiday, 0 if not",
                               example=0, ge=0, le=1)
    month        : int = Field(..., description="Month number (3=March, 4=April)",
                               example=4, ge=1, le=12)
    day_of_month : int = Field(..., description="Day of month (1-31)",
                               example=15, ge=1, le=31)
    week_of_month: int = Field(..., description="Week number of the month",
                               example=3, ge=1, le=6)

class BatchInput(BaseModel):
    predictions: List[PredictionInput]

# ── Helper: build feature vector ─────────────────────────────────────────────

def build_feature_vector(data: PredictionInput) -> np.ndarray:
    """
    Converts raw user input into the exact feature vector the model expects.
    Steps:
      1. Validate inputs
      2. Create one-hot encoded row matching training column structure
      3. Apply StandardScaler transformation
    """
    # Validate
    if data.dish_name not in VALID_DISHES:
        raise HTTPException(
            status_code=422,
            detail=f"Invalid dish_name '{data.dish_name}'. "
                   f"Valid options: {VALID_DISHES}"
        )
    if data.day_of_week not in VALID_DAYS:
        raise HTTPException(
            status_code=422,
            detail=f"Invalid day_of_week '{data.day_of_week}'. "
                   f"Valid options: {VALID_DAYS}"
        )
    if data.weather not in VALID_WEATHER:
        raise HTTPException(
            status_code=422,
            detail=f"Invalid weather '{data.weather}'. "
                   f"Valid options: {VALID_WEATHER}"
        )

    # Build a single-row DataFrame with the same structure as training data
    raw = {
        'is_holiday'   : data.is_holiday,
        'month'        : data.month,
        'day_of_month' : data.day_of_month,
        'week_of_month': data.week_of_month,
        f'dish_name_{data.dish_name}'   : 1,
        f'day_of_week_{data.day_of_week}': 1,
        f'weather_{data.weather}'       : 1,
    }

    # Create DataFrame with ALL feature columns, defaulting missing to 0
    row = pd.DataFrame([raw]).reindex(columns=feature_cols, fill_value=0)

    # Apply the saved StandardScaler
    row_scaled = scaler.transform(row)

    return row_scaled

