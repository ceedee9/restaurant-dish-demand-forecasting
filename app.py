# ── ENDPOINT 3: Single prediction ────────────────────────────────────────────

@app.post("/predict")
def predict(data: PredictionInput):
    """
    Predicts how many servings of a dish to prepare.

    Input: dish name, day of week, weather, holiday flag, date info
    Output: predicted quantity_sold (servings to prepare)
    """
    try:
        row_scaled = build_feature_vector(data)
        prediction = model.predict(row_scaled)[0]
        servings   = max(1, round(float(prediction)))

        return {
            "status"      : "success",
            "model"       : f"{type(model).__name__} (Optimized)",
            "input"       : {
                "dish_name"    : data.dish_name,
                "day_of_week"  : data.day_of_week,
                "weather"      : data.weather,
                "is_holiday"   : data.is_holiday,
                "date_info"    : f"Month {data.month}, Day {data.day_of_month}",
            },
            "prediction"  : {
                "raw_value"     : round(float(prediction), 4),
                "servings"      : servings,
                "recommendation": f"Prepare {servings} servings of {data.dish_name}",
            }
        }
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))

# ── ENDPOINT 4: Batch prediction ─────────────────────────────────────────────

@app.post("/predict-batch")
def predict_batch(data: BatchInput):
    """
    Predicts servings for multiple dish-day combinations at once.
    Useful for planning the full daily menu in one request.
    """
    try:
        results = []
        for i, item in enumerate(data.predictions):
            row_scaled = build_feature_vector(item)
            prediction = model.predict(row_scaled)[0]
            servings   = max(1, round(float(prediction)))
            results.append({
                "row"           : i + 1,
                "dish_name"     : item.dish_name,
                "day_of_week"   : item.day_of_week,
                "weather"       : item.weather,
                "is_holiday"    : item.is_holiday,
                "predicted_raw" : round(float(prediction), 4),
                "servings"      : servings,
                "recommendation": f"Prepare {servings} servings"
            })

        total_servings = sum(r["servings"] for r in results)
        return {
            "status"         : "success",
            "model"          : f"{type(model).__name__} (Optimized)",
            "total_dishes"   : len(results),
            "total_servings" : total_servings,
            "predictions"    : results
        }
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))

